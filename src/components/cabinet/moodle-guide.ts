import type { DownloadKind } from '../../content/schemas/downloads';

export type InlinePart = { readonly kind: 'text' | 'strong' | 'code'; readonly text: string };

const INLINE = /\*([^*]+)\*|`([^`]+)`/g;

export function inlineParts(text: string): InlinePart[] {
  const parts: InlinePart[] = [];
  let last = 0;
  for (const match of text.matchAll(INLINE)) {
    const start = match.index ?? 0;
    if (start > last) parts.push({ kind: 'text', text: text.slice(last, start) });
    parts.push(match[1] !== undefined ? { kind: 'strong', text: match[1] } : { kind: 'code', text: match[2] ?? '' });
    last = start + match[0].length;
  }
  if (last < text.length) parts.push({ kind: 'text', text: text.slice(last) });
  return parts;
}

